/** Escapa texto antes de o colocar em HTML. O React já escapa texto nos nós; isto cobre emails e HTML gerado no servidor. */
export function escapeHtml(value: unknown) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
